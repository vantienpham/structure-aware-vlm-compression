#!/usr/bin/env python3
"""Collect per-run result.json files into a committed summary table.

Run on the cluster, where the runs live::

    uv run --no-sync python scripts/collect_results.py \
        --runs out/runs --out results/tables/scienceqa.md

`out/` is cluster-only and gitignored; `results/tables/` is what
`slurm/sync.sh pull` brings back and what gets committed, so every number in
the manuscript traces to a file under version control.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
from pathlib import Path

COLUMNS = [
    ("run", lambda r: r["_run"]),
    ("search", lambda r: r.get("search") or "-"),
    ("bias", lambda r: r.get("bias_mode") or "-"),
    ("svd", lambda r: r.get("svd") or "-"),
    ("target", lambda r: f"{r.get('ratio', float('nan')):.2f}"),
    ("actual", lambda r: _fmt(r.get("param_ratio_actual"), "{:.3f}")),
    ("acc %", lambda r: _fmt(r.get("eval", {}).get("accuracy"), "{:.2%}")),
    ("n", lambda r: str(r.get("eval", {}).get("n", "-"))),
    ("nonfinite", lambda r: str(r.get("eval", {}).get("n_nonfinite", "-"))),
    ("vision", lambda r: _fmt(r.get("mean_ratio_by_tower", {}).get("vision"), "{:.3f}")),
    ("language", lambda r: _fmt(r.get("mean_ratio_by_tower", {}).get("language"), "{:.3f}")),
    ("projector", lambda r: _fmt(r.get("mean_ratio_by_tower", {}).get("projector"), "{:.3f}")),
    ("min", lambda r: _fmt(r.get("wall_minutes"), "{:.1f}")),
]


def _fmt(value, spec: str) -> str:
    return spec.format(value) if isinstance(value, (int, float)) else "-"


def load_runs(runs_dir: Path) -> list[dict]:
    results = []
    for path in sorted(runs_dir.glob("*/result.json")):
        try:
            with open(path) as f:
                record = json.load(f)
        except (OSError, json.JSONDecodeError) as exc:
            print(f"  skipping {path}: {exc}")
            continue
        record["_run"] = path.parent.name
        results.append(record)
    return results


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", default="out/runs")
    parser.add_argument("--out", default="results/tables/scienceqa.md")
    args = parser.parse_args(argv)

    records = load_runs(Path(args.runs))
    if not records:
        print(f"no result.json found under {args.runs}")
        return 1

    # Baselines first, then by target ratio descending (least to most aggressive).
    records.sort(key=lambda r: (r.get("search") is not None, -r.get("ratio", 0)))

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    headers = [name for name, _ in COLUMNS]
    rows = [[fn(r) for _, fn in COLUMNS] for r in records]

    with open(args.out, "w") as f:
        f.write("# ScienceQA-IMG results\n\n")
        f.write("Generated by `scripts/collect_results.py`. "
                "`vision`/`language`/`projector` are mean retained parameter "
                "ratios per tower -- the diagnostic for whether allocation "
                "actually differs across towers.\n\n")
        f.write("| " + " | ".join(headers) + " |\n")
        f.write("|" + "|".join(["---"] * len(headers)) + "|\n")
        for row in rows:
            f.write("| " + " | ".join(row) + " |\n")

    csv_path = os.path.splitext(args.out)[0] + ".csv"
    with open(csv_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows(rows)

    print(f"wrote {args.out} and {csv_path} ({len(records)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
